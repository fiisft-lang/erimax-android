-- Banco mínimo isolado para validar a migration de dupla função.
DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
END;
$roles$;

CREATE SCHEMA IF NOT EXISTS auth;
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;

CREATE TABLE public.perfis (
  id uuid PRIMARY KEY,
  nome text NOT NULL,
  perfil text NOT NULL
);
CREATE TABLE public.status_tecnicos (
  user_id uuid PRIMARY KEY,
  status text,
  turno_ativo boolean NOT NULL DEFAULT false
);
CREATE TABLE public.os (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text,
  tecnico text,
  transferencia_para text,
  transferencia_solicitada_por text,
  transferencia_solicitada_em timestamptz,
  transferencia_motivo text,
  tipo text,
  tecnicos_participantes jsonb,
  maquinas_execucao jsonb
);
CREATE TABLE public.historico_transferencias_os (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  os_id bigint NOT NULL,
  tecnico_anterior text,
  tecnico_novo text,
  solicitada_por text,
  solicitada_em timestamptz,
  aceita_por text,
  aceita_em timestamptz,
  motivo text
);
