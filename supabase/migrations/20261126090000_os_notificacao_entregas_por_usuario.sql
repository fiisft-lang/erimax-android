-- Controle de entrega de notificações normais de O.S. por destinatário.
-- Não aplicar em produção durante a auditoria; esta migração pertence à branch de testes.

create table if not exists public.os_notificacao_entregas (
  id bigint generated by default as identity primary key,
  os_id bigint not null references public.os(id) on delete cascade,
  user_id uuid not null references public.perfis(id) on delete cascade,
  status text not null default 'pendente'
    check (status in ('pendente','processando','enviado','dispensado')),
  tentativas integer not null default 0 check (tentativas >= 0),
  proxima_tentativa_em timestamptz not null default now(),
  claim_em timestamptz,
  enviado_em timestamptz,
  ultimo_erro text,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint os_notificacao_entregas_os_usuario_uidx unique (os_id,user_id)
);

create index if not exists os_notificacao_entregas_pendentes_idx
  on public.os_notificacao_entregas (user_id,proxima_tentativa_em)
  where status in ('pendente','processando');

alter table public.os_notificacao_entregas enable row level security;
revoke all on public.os_notificacao_entregas from public, anon, authenticated;
grant all on public.os_notificacao_entregas to service_role;
grant usage, select on sequence public.os_notificacao_entregas_id_seq to service_role;
