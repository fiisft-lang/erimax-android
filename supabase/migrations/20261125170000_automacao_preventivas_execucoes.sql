-- Estrutura idempotente para automação de O.S. de preventiva.
-- Esta migration é somente proposta em branch; não foi aplicada ao banco de produção.

create table if not exists public.preventiva_execucoes (
  id bigint generated by default as identity primary key,
  preventiva_id bigint not null,
  data_vencimento date not null,
  data_geracao date not null,
  os_id bigint unique references public.os(id) on delete set null,
  gerada_em timestamptz,
  prazo_em timestamptz not null,
  status text not null default 'aguardando'
    check (status in ('aguardando','aberta','concluida','atrasada')),
  atraso_notificado_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint preventiva_execucoes_ciclo_uidx unique (preventiva_id, data_vencimento)
);

create index if not exists preventiva_execucoes_status_prazo_idx
  on public.preventiva_execucoes (status, prazo_em);

create table if not exists public.preventiva_lembretes_enviados (
  id bigint generated by default as identity primary key,
  execucao_id bigint not null references public.preventiva_execucoes(id) on delete cascade,
  horario timestamptz not null,
  destinatarios jsonb not null default '[]'::jsonb,
  enviado_em timestamptz not null default now(),
  constraint preventiva_lembretes_execucao_horario_uidx unique (execucao_id, horario),
  constraint preventiva_lembretes_destinatarios_array_check
    check (jsonb_typeof(destinatarios) = 'array')
);

alter table public.os
  add column if not exists prazo_preventiva_em timestamptz,
  add column if not exists preventiva_atrasada boolean not null default false;

create index if not exists os_preventiva_atrasada_idx
  on public.os (preventiva_atrasada)
  where preventiva_atrasada = true;

alter table public.preventiva_execucoes enable row level security;
alter table public.preventiva_lembretes_enviados enable row level security;

revoke all on public.preventiva_execucoes from anon, authenticated;
revoke all on public.preventiva_lembretes_enviados from anon, authenticated;
