-- Estrutura idempotente para automação de O.S. de preventiva.
-- Esta migration permanece somente na branch de testes; não aplicar em produção antes da aprovação.

create table if not exists public.preventiva_execucoes (
  id bigint generated by default as identity primary key,
  preventiva_id bigint not null references public.preventivas(id) on delete cascade,
  data_vencimento date not null,
  data_geracao date not null,
  os_id bigint unique references public.os(id) on delete set null,
  gerada_em timestamptz,
  geracao_claim_em timestamptz,
  prazo_em timestamptz not null,
  status text not null default 'aguardando'
    check (status in ('aguardando','gerando','aberta','concluida','atrasada','cancelada')),
  atraso_notificado_em timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  constraint preventiva_execucoes_ciclo_uidx unique (preventiva_id, data_vencimento)
);

create index if not exists preventiva_execucoes_status_prazo_idx
  on public.preventiva_execucoes (status, prazo_em);

create table if not exists public.preventiva_lembretes_enviados (
  id bigint generated by default as identity primary key,
  execucao_id bigint not null references public.preventiva_execucoes(id) on delete cascade,
  slot_key text not null,
  horario timestamptz not null,
  destinatarios jsonb not null default '[]'::jsonb,
  status text not null default 'processando'
    check (status in ('processando','enviado')),
  enviado_em timestamptz,
  criado_em timestamptz not null default now(),
  constraint preventiva_lembretes_execucao_slot_uidx unique (execucao_id, slot_key),
  constraint preventiva_lembretes_destinatarios_array_check
    check (jsonb_typeof(destinatarios) = 'array')
);

create index if not exists preventiva_lembretes_execucao_idx
  on public.preventiva_lembretes_enviados (execucao_id, horario);

alter table public.os
  add column if not exists prazo_preventiva_em timestamptz,
  add column if not exists preventiva_atrasada boolean not null default false;

create index if not exists os_preventiva_atrasada_idx
  on public.os (preventiva_atrasada)
  where preventiva_atrasada = true;

alter table public.preventiva_execucoes enable row level security;
alter table public.preventiva_lembretes_enviados enable row level security;

revoke all on public.preventiva_execucoes from anon, authenticated;
revoke all on public.preventiva_lembretes_enviados from anon, authenticated;
grant all on public.preventiva_execucoes to service_role;
grant all on public.preventiva_lembretes_enviados to service_role;
grant usage, select on sequence public.preventiva_execucoes_id_seq to service_role;
grant usage, select on sequence public.preventiva_lembretes_enviados_id_seq to service_role;

-- Mantém o estado da execução alinhado à O.S. sem depender de uma gravação
-- adicional do aplicativo cliente ao concluir ou cancelar a ordem.
create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to service_role;

create or replace function private.sincronizar_execucao_preventiva_os()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public, private
as $$
begin
  if new.preventiva_id is null then
    return new;
  end if;

  if new.status = 'Concluída' then
    update public.preventiva_execucoes
       set status = 'concluida',
           atualizado_em = now()
     where os_id = new.id
       and status <> 'concluida';

    if new.preventiva_atrasada then
      update public.os set preventiva_atrasada = false where id = new.id;
    end if;
  elsif new.status = 'Cancelada' then
    update public.preventiva_execucoes
       set status = 'cancelada',
           atualizado_em = now()
     where os_id = new.id
       and status not in ('concluida','cancelada');
  end if;

  return new;
end;
$$;

revoke all on function private.sincronizar_execucao_preventiva_os() from public, anon, authenticated;
grant execute on function private.sincronizar_execucao_preventiva_os() to service_role;

drop trigger if exists trg_sincronizar_execucao_preventiva_os on public.os;
create trigger trg_sincronizar_execucao_preventiva_os
after update of status on public.os
for each row
when (old.status is distinct from new.status and new.preventiva_id is not null)
execute function private.sincronizar_execucao_preventiva_os();
